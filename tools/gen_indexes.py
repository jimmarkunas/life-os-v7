"""LIFE-1098: INDEX.md, docs/index.json, docs/README.md and docs/DECISIONS_INDEX.md are generated; nobody edits them by hand.

  docs/DECISIONS_INDEX.md  one line per `## D<n> ...` heading of docs/DECISIONS.md (a decision whose body says `Amends D<m>.` marks D<m> `(amended by D<n>)`)
  INDEX.md, docs/index.json, docs/README.md  from the one hand-edited file docs/index-source.json

Add a decision: write its heading in docs/DECISIONS.md (number from `python -m lifeos.sources.devtools.decisions claim`), then run this.
Add a doc or a global source: add one line (docs_readme_sections) or one object (sources) to docs/index-source.json, then run this.

    python tools/gen_indexes.py            write the four files
    python tools/gen_indexes.py --check    change nothing; exit 1 and name the stale files (tests/contracts/test_generated_indexes.py runs this)

tools/preflight.sh runs it, so a PR never carries a hand edit. Stdlib only."""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/index-source.json"
NOTE = "<!-- generated by tools/gen_indexes.py: do not edit; {how} -->"
DECISION_HEAD = re.compile(r"^## (D\d+)\b")
AMENDS = re.compile(r"^Amends (D\d+)\b")


def decisions_index(decisions_text):
    """The DECISIONS_INDEX.md text for a DECISIONS.md text."""
    heads, amended, current = [], {}, None
    for line in decisions_text.splitlines():
        found = DECISION_HEAD.match(line)
        if found:
            current = found.group(1)
            heads.append((current, line[3:].strip()))
        elif current and AMENDS.match(line):
            amended.setdefault(AMENDS.match(line).group(1), []).append(current)
    lines = []
    for key, title in heads:
        by = amended.get(key)
        lines.append(f"- {title}" + (f" (amended by {', '.join(by)})" if by else ""))
    return (
        "# Decision index\n\n"
        + NOTE.format(how="add the decision's `## D<n>` heading to docs/DECISIONS.md, then run it")
        + "\n\nOne line per decision in `docs/DECISIONS.md`. Do not read that file whole: find the number here, then "
        '`grep -n "^## D<n> " -A6 docs/DECISIONS.md`.\n\n' + "\n".join(lines) + "\n"
    )


def index_md(src):
    head = list(src["index_md_head"])
    head.insert(1, "\n" + NOTE.format(how="edit docs/index-source.json"))
    rows = [
        "| Path | Authority | Purpose | Owner | Retrieval |",
        "|---|---|---|---|---|",
    ] + [
        f"| [`{s['path']}`]({s['path']}) | {s['authority']} | {s['purpose']} | {s['owner']} | {s['retrieval']} |"
        for s in src["sources"]
    ]
    return (
        "\n".join(head)
        + "\n\n## Global sources\n\n"
        + "\n".join(rows)
        + "\n\n"
        + "\n".join(src["index_md_tail"])
        + "\n"
    )


def index_json(src):
    data = {
        "about": src["index_json_about"],
        "master": src["master"],
        "sources": src["sources"],
        "external_resources": src["external_resources"],
    }
    return json.dumps(data, indent=1, ensure_ascii=False) + "\n"


def docs_readme(src):
    head = list(src["docs_readme_head"])
    head.insert(1, "\n" + NOTE.format(how="edit docs/index-source.json"))
    out = "\n".join(head) + "\n"
    for section in src["docs_readme_sections"]:
        out += f"\n## {section['title']}\n\n" + "\n".join(section["lines"]) + "\n"
    return out


def outputs():
    src = json.loads(SOURCE.read_text())
    return {
        "INDEX.md": index_md(src),
        "docs/index.json": index_json(src),
        "docs/README.md": docs_readme(src),
        "docs/DECISIONS_INDEX.md": decisions_index((ROOT / "docs/DECISIONS.md").read_text()),
    }


def stale():
    return [name for name, text in outputs().items() if not (ROOT / name).exists() or (ROOT / name).read_text() != text]


def main(argv):
    if argv == ["--check"]:
        names = stale()
        if names:
            print("stale; run python tools/gen_indexes.py: " + ", ".join(names), file=sys.stderr)
        return 1 if names else 0
    if argv:
        print(__doc__, file=sys.stderr)
        return 2
    for name, text in outputs().items():
        path = ROOT / name
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            print(f"gen_indexes: wrote {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
