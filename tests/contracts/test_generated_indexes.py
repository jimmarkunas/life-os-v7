"""LIFE-1098: INDEX.md, docs/index.json, docs/README.md and docs/DECISIONS_INDEX.md are generated, never hand-edited."""

import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))

import gen_indexes  # noqa: E402


class GeneratedIndexes(unittest.TestCase):
    def test_the_four_files_match_the_generator(self):
        self.assertEqual(gen_indexes.stale(), [], "stale; run python tools/gen_indexes.py")

    def test_every_generated_file_says_so(self):
        for name in ("INDEX.md", "docs/README.md", "docs/DECISIONS_INDEX.md"):
            self.assertIn("generated by tools/gen_indexes.py", (ROOT / name).read_text(), name)
        self.assertIn("tools/gen_indexes.py", (ROOT / "docs/index.json").read_text())

    def test_a_decision_heading_becomes_one_line_and_an_amendment_is_marked(self):
        text = "## D1 — One (2026)\nbody\n## D2 — Two (2026)\nAmends D1. Why.\n"
        out = gen_indexes.decisions_index(text)
        self.assertIn("\n- D1 — One (2026) (amended by D2)\n- D2 — Two (2026)\n", out)

    def test_preflight_regenerates_them(self):
        self.assertIn("gen_indexes", (ROOT / "tools/regen.py").read_text())
        self.assertIn("--regen", (ROOT / "tools/preflight.sh").read_text())


if __name__ == "__main__":
    unittest.main()
